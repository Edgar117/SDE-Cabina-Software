const LEGACY_THEME_MAP = {
  fiesta: 'fiesta-moderna',
};

export function getTheme(id) {
  const resolved = LEGACY_THEME_MAP[id] || id;
  return themes[resolved] || themes.teatro;
}

export function applyTheme(themeId) {
  const theme = getTheme(themeId);
  const root = document.documentElement;

  root.style.setProperty('--stage-bg', theme.ui.stageBg);
  root.style.setProperty('--curtain-deep', theme.ui.curtainDeep);
  root.style.setProperty('--gold', theme.ui.gold);
  root.style.setProperty('--gold-light', theme.ui.goldLight);
  root.style.setProperty('--btn-inner', theme.ui.btnInner);
  root.style.setProperty('--btn-outer', theme.ui.btnOuter);
  root.style.setProperty('--fold-opacity', String(theme.ui.foldOpacity ?? 0.5));

  document.body.dataset.theme = theme.id;
}

export function getStripColors(branding) {
  const theme = getTheme(branding.themeId);
  return {
    ...theme.strip,
    accent: branding.accentColor || theme.strip.accent,
  };
}
